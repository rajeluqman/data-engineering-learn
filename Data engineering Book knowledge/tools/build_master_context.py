"""
Builds MASTER_CONTEXT.md — router + inventory + source status + coverage + unresolved.

All factual tables are GENERATED from SOURCE_REGISTER.csv, PAGE_MANIFEST.csv,
CHAPTER_MAP.csv, chapter_stats.json, FLAG_LEDGER.csv. Hand-written prose (the web
corpus table, narrative notes) lives inside <!-- PROSE:key:START/END --> blocks that
this script preserves verbatim across regenerations -- everything outside those blocks
is overwritten every run. This is the fix for defect class 5 (a hand-maintained status
table went stale/self-contradictory within one session).

Run with the D-drive venv:
  .tools/venv/Scripts/python.exe "Data engineering Book knowledge/tools/build_master_context.py"
"""
import csv
import io
import json
import os
import re
import sys
from collections import Counter

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", errors="replace")

BOOK_DIR = os.path.join(os.path.dirname(__file__), "..")
AUDIT_DIR = os.path.join(BOOK_DIR, "audit")
OUT_PATH = os.path.join(BOOK_DIR, "MASTER_CONTEXT.md")

PROSE_RE = re.compile(
    r"<!-- PROSE:(\w+):START -->(.*?)<!-- PROSE:\1:END -->", re.S
)


def load_csv(name):
    with open(os.path.join(AUDIT_DIR, name), encoding="utf-8") as f:
        return list(csv.DictReader(f))


def load_prose_blocks(existing_text):
    """Extract previously-saved hand-written prose blocks so a rebuild doesn't erase them."""
    blocks = {}
    if existing_text:
        for m in PROSE_RE.finditer(existing_text):
            blocks[m.group(1)] = m.group(2)
    return blocks


def prose_block(key, blocks, default):
    body = blocks.get(key, default)
    return f"<!-- PROSE:{key}:START -->{body}<!-- PROSE:{key}:END -->"


def main():
    source_reg = load_csv("SOURCE_REGISTER.csv")
    page_manifest = load_csv("PAGE_MANIFEST.csv")
    chapter_map = load_csv("CHAPTER_MAP.csv")
    flag_ledger = load_csv("FLAG_LEDGER.csv")
    with open(os.path.join(AUDIT_DIR, "chapter_stats.json"), encoding="utf-8") as f:
        chapter_stats = json.load(f)

    existing = ""
    if os.path.exists(OUT_PATH):
        with io.open(OUT_PATH, encoding="utf-8") as f:
            existing = f.read()
    prose = load_prose_blocks(existing)

    out = []
    out.append("# DE Master Library — MASTER CONTEXT\n")
    out.append("> **Router + inventory + status.** Generated by `tools/build_master_context.py` "
                "from `audit/*.csv` and `audit/chapter_stats.json`. Tables below are regenerated "
                "every run; only the marked prose blocks survive a rebuild.\n\n")
    out.append("Full nota per chapter: `notes/<source_id>/`. Full concatenation: "
                "`MASTER_CONTEXT_FULL.md` (also generated — never hand-edit either file).\n\n")
    out.append("---\n\n## 1. Source Inventory\n\n")
    out.append("| source_id | filename | pages | sha256 (16) | source_type |\n|---|---|---:|---|---|\n")
    total_pages = 0
    for r in source_reg:
        total_pages += int(r["pdf_page_count_measured"])
        out.append(f"| `{r['source_id']}` | {r['exact_filename']} | {r['pdf_page_count_measured']} "
                    f"| `{r['sha256'][:16]}` | {r['source_type']} |\n")
    out.append(f"\n**Total measured pages: {total_pages}**\n\n")

    out.append("---\n\n## 2. Page Coverage (of {} pages)\n\n".format(len(page_manifest)))
    status_counts = Counter(r["review_status"] for r in page_manifest)
    out.append("| review_status | count | % |\n|---|---:|---:|\n")
    for k, v in sorted(status_counts.items(), key=lambda x: -x[1]):
        out.append(f"| {k} | {v} | {100*v/len(page_manifest):.1f}% |\n")

    out.append("\n### Open flags (`FLAG_LEDGER.csv`)\n\n")
    open_flags = [r for r in flag_ledger if not r["disposition"]]
    disp_counts = Counter(r["disposition"] or "(open)" for r in flag_ledger)
    out.append("| disposition | count |\n|---|---:|\n")
    for k, v in sorted(disp_counts.items(), key=lambda x: -x[1]):
        out.append(f"| {k} | {v} |\n")
    out.append(f"\n**{len(open_flags)} flagged pages have no disposition yet** "
                "(see `audit/FLAG_LEDGER.csv`).\n\n")

    out.append("---\n\n## 3. Chapter Synthesis Progress\n\n")
    in_scope = [r for r in chapter_map if r["in_synthesis_scope"] == "True"]
    synth = [r for r in in_scope if r["status"] == "synthesized"]
    out.append(f"**{len(synth)} / {len(in_scope)}** in-scope chapters synthesized.\n\n")
    band_counts = Counter(s["band"] for s in chapter_stats)
    remaining_units = 0
    unit_map = {"short": 1, "medium": 5, "long": 9}
    done_units = 0
    for s in chapter_stats:
        u = unit_map.get(s["band"], 1)
        if s.get("status") == "synthesized":
            done_units += u
        else:
            remaining_units += u
    out.append(f"Effort units (band-weighted, see EXECUTION_SPEC.md C1): "
                f"**{done_units} done / {remaining_units} remaining** "
                f"(bands: {dict(band_counts)}).\n\n")
    out.append("| source_id | synthesized | in-scope chapters |\n|---|---:|---:|\n")
    by_source_scope = Counter(r["source_id"] for r in in_scope)
    by_source_synth = Counter(r["source_id"] for r in synth)
    for sid in sorted(by_source_scope):
        out.append(f"| `{sid}` | {by_source_synth.get(sid,0)} | {by_source_scope[sid]} |\n")

    out.append("\n---\n\n## 4. Source Identity Findings (summary — full detail in `audit/GAPS_AND_VERIFICATION.md`)\n\n")
    out.append("| source_id | finding |\n|---|---|\n")
    for r in source_reg:
        note = r["note"][:140].replace("|", "/")
        out.append(f"| `{r['source_id']}` | {note} |\n")

    out.append("\n---\n\n## 5. Web Reference Corpus\n\n")
    web_default = (
        "\n\n**PENDING_INPUT.** The 10 supplied reference rows have not yet been carried "
        "into this file from the prior catalog "
        "(`DATA_ENGINEERING_MASTER_LIBRARY_SOURCE_OF_TRUTH.md` §4). Paste them here "
        "verbatim (tracking params intact) when doing so — do not summarize or reword.\n\n"
    )
    out.append(prose_block("web_corpus", prose, web_default))

    out.append("\n\n---\n\n## 6. Known Gaps\n\nSee `audit/GAPS_AND_VERIFICATION.md` for the full, current gap list. "
                "Do not duplicate it here by hand — it drifts (see EXECUTION_SPEC.md defect class 5).\n")

    with io.open(OUT_PATH, "w", encoding="utf-8", newline="\n") as f:
        f.write("".join(out))

    print(f"wrote {OUT_PATH}")
    print(f"prose blocks preserved: {list(prose.keys())}")


if __name__ == "__main__":
    main()
