"""
Builds MASTER_CONTEXT_FULL.md by concatenating notes/**/*.md in a fixed order.

GENERATED FILE -- never edit MASTER_CONTEXT_FULL.md by hand. Edit the source note in
notes/<source_id>/ and re-run this script.

Asserts (fail loudly rather than emit a silently incomplete file):
  1. Every chapter marked `status: synthesized` in CHAPTER_MAP.csv has a corresponding
     note file that this script actually included.
  2. Every note file found on disk under notes/ was included (no orphans skipped).

Run with the D-drive venv:
  .tools/venv/Scripts/python.exe "Data engineering Book knowledge/tools/build_full.py"
"""
import csv
import glob
import hashlib
import io
import os
import sys

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", errors="replace")

BOOK_DIR = os.path.join(os.path.dirname(__file__), "..")
NOTES_DIR = os.path.join(BOOK_DIR, "notes")
AUDIT_DIR = os.path.join(BOOK_DIR, "audit")

# Fixed source order per user decision (see EXECUTION_SPEC.md C2).
SOURCE_ORDER = [
    "fundamentals_de", "kimball_dwtoolkit_3e", "ddia_kleppmann", "airflow_2e",
    "streaming_systems", "databricks_big_book_4e", "database_internals_petrov",
]


def note_source_id(path):
    return os.path.relpath(path, NOTES_DIR).split(os.sep)[0]


def note_start_page(path):
    """Read the note's own declared PDF page range to sort chapters within a source."""
    with io.open(path, encoding="utf-8") as f:
        for line in f:
            if "PDF page range" in line or "pdf page range" in line.lower():
                # e.g. "**PDF page range:** 28-57 (30 pages)"
                digits = "".join(c if c.isdigit() else " " for c in line)
                nums = [int(x) for x in digits.split()]
                if nums:
                    return nums[0]
    return 0


def main():
    all_notes = sorted(glob.glob(os.path.join(NOTES_DIR, "**", "*.md"), recursive=True))
    by_source = {}
    for p in all_notes:
        by_source.setdefault(note_source_id(p), []).append(p)

    ordered = []
    for sid in SOURCE_ORDER:
        for p in sorted(by_source.get(sid, []), key=note_start_page):
            ordered.append(p)
    # any source not in SOURCE_ORDER still gets included (never silently drop a note)
    leftover_sources = set(by_source) - set(SOURCE_ORDER)
    for sid in sorted(leftover_sources):
        ordered.extend(sorted(by_source[sid]))

    assert len(ordered) == len(all_notes), (
        f"orphan notes not included: {set(all_notes) - set(ordered)}"
    )

    out = io.StringIO()
    out.write("# MASTER CONTEXT — FULL (GENERATED)\n\n")
    out.write("> **This file is generated by `tools/build_full.py`. Do not edit by hand.**\n")
    out.write("> Edit the source note under `notes/<source_id>/` and re-run the script.\n\n")
    out.write("| Note file | SHA-256 (first 16) |\n|---|---|\n")
    hashes = {}
    for p in ordered:
        h = hashlib.sha256(io.open(p, "rb").read()).hexdigest()[:16]
        hashes[p] = h
        out.write(f"| `{os.path.relpath(p, BOOK_DIR)}` | `{h}` |\n")
    out.write("\n---\n\n")

    for p in ordered:
        rel = os.path.relpath(p, BOOK_DIR)
        out.write(f"<!-- SOURCE: {rel}  sha256:{hashes[p]} -->\n\n")
        with io.open(p, encoding="utf-8") as f:
            out.write(f.read())
        out.write("\n\n---\n\n")

    out_path = os.path.join(BOOK_DIR, "MASTER_CONTEXT_FULL.md")
    with io.open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(out.getvalue())

    # ---- assertion 1: every synthesized chapter-map entry has an included note ----
    # (best-effort match: chapter map doesn't yet track a note filename, so this
    # checks the weaker but still useful invariant that at least one note exists
    # for every source_id that has any status != 'unresolved'/'located' entries
    # once notes start tracking chapter-level status explicitly.)
    with open(os.path.join(AUDIT_DIR, "CHAPTER_MAP.csv"), encoding="utf-8") as f:
        chapter_rows = list(csv.DictReader(f))
    synthesized_sources = {r["source_id"] for r in chapter_rows if r.get("status") == "synthesized"}
    missing = synthesized_sources - set(by_source)
    assert not missing, f"chapter map claims 'synthesized' status for sources with no notes: {missing}"

    print(f"wrote {out_path}")
    print(f"included {len(ordered)} note files from {len(by_source)} sources")
    print("order:", [os.path.relpath(p, NOTES_DIR) for p in ordered])


if __name__ == "__main__":
    main()
